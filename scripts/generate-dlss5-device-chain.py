#!/usr/bin/env python3
"""Generate device pNext copying/feature promotion from the installed Vulkan registry."""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

root = ET.parse(sys.argv[1]).getroot()
types = root.findall('./types/type')
structs = {t.get('name'): t for t in types if t.get('category') == 'struct' and not t.get('alias')}
# Only types advertised by Vulkan (not Vulkan SC), guarded by their defining API/extension.
guards = {}
for owner in list(root.findall('./feature')) + list(root.findall('./extensions/extension')):
    api = owner.get('api', owner.get('supported', ''))
    if 'vulkan' not in api.split(','):
        continue
    for req in owner.findall('require'):
        if req.get('api') not in (None, 'vulkan'):
            continue
        for t in req.findall('type'):
            guard = ('VK_VERSION_' + owner.get('number').replace('.', '_')
                     if owner.tag == 'feature' else owner.get('name'))
            guards.setdefault(t.get('name'), guard)

out = ['// Generated by scripts/generate-dlss5-device-chain.py; do not edit.',
       'static size_t deviceChainSize(VkStructureType type) {', '  switch (type) {',
       '  case VK_STRUCTURE_TYPE_LOADER_DEVICE_CREATE_INFO: return sizeof(VkLayerDeviceCreateInfo);']
for name, t in structs.items():
    if not set(t.get('structextends', '').split(',')) & {'VkDeviceCreateInfo', 'VkPhysicalDeviceFeatures2'}:
        continue
    member = t.find("member/[name='sType']")
    if member is None or not member.get('values') or name not in guards:
        continue
    guard = guards[name]
    protect = t.get('protect')
    out += [f'#if defined({guard})' + (f' && defined({protect})' if protect else ''),
            f'  case {member.get("values")}: return sizeof({name});', '#endif']
out += ['  default: return 0;', '  }', '}']
# Explicit promoted feature families: preserve every application bit when replacing
# their individual representation with the corresponding Vulkan 1.1/1.2/1.3 structure.
families = {
    '11': ['16BitStorage', 'Multiview', 'VariablePointers', 'ProtectedMemory', 'SamplerYcbcrConversion', 'ShaderDrawParameters'],
    '12': ['8BitStorage', 'ShaderAtomicInt64', 'ShaderFloat16Int8', 'DescriptorIndexing', 'ScalarBlockLayout', 'ImagelessFramebuffer', 'UniformBufferStandardLayout', 'ShaderSubgroupExtendedTypes', 'SeparateDepthStencilLayouts', 'HostQueryReset', 'TimelineSemaphore', 'BufferDeviceAddress', 'VulkanMemoryModel'],
    '13': ['ImageRobustness', 'InlineUniformBlock', 'PipelineCreationCacheControl', 'PrivateData', 'ShaderDemoteToHelperInvocation', 'ShaderTerminateInvocation', 'SubgroupSizeControl', 'Synchronization2', 'TextureCompressionASTCHDR', 'ZeroInitializeWorkgroupMemory', 'DynamicRendering', 'ShaderIntegerDotProduct', 'Maintenance4'],
}
out += ['static std::pair<size_t, size_t> deviceFeatureRange(VkStructureType type) {', '  switch (type) {']
for name, t in structs.items():
    if name not in guards or not set(t.get('structextends', '').split(',')) & {'VkDeviceCreateInfo', 'VkPhysicalDeviceFeatures2'}:
        continue
    members = [m for m in t.findall('member') if m.findtext('name') not in ('sType', 'pNext')]
    if not members or any(m.findtext('type') != 'VkBool32' for m in members):
        continue
    stype = t.find("member/[name='sType']").get('values')
    protect = t.get('protect')
    out += [f'#if defined({guards[name]})' + (f' && defined({protect})' if protect else ''),
            f'  case {stype}: return {{offsetof({name}, {members[0].findtext("name")}), offsetof({name}, {members[-1].findtext("name")}) + sizeof(VkBool32)}};',
            '#endif']
out += ['  default: return {0, 0};', '  }', '}']
out += ['static bool promoteDeviceFeatures(const VkBaseInStructure* node, vk::DeviceRequirements& req) {', '  switch (node->sType) {']
for version, names in families.items():
    core = structs['VkPhysicalDeviceVulkan' + version + 'Features']
    core_fields = {m.findtext('name') for m in core.findall('member')}
    for suffix in names:
        name = 'VkPhysicalDevice' + suffix + 'Features'
        t = structs[name]
        stype = t.find("member/[name='sType']").get('values')
        out += [f'  case {stype}: {{', f'    const auto& source = *reinterpret_cast<const {name}*>(node);']
        for m in t.findall('member'):
            field = m.findtext('name')
            if m.findtext('type') == 'VkBool32':
                if field not in core_fields:
                    raise ValueError(f'{name}.{field} has no promoted field')
                out += [f'    req.f{version}.{field} |= source.{field};']
        out += ['    return true;', '  }']
out += ['  default: return false;', '  }', '}']
Path(sys.argv[2]).write_text('\n'.join(out) + '\n')
