#!/usr/bin/env bash
# Configure, build and stage an i686 layer with Zig as the cross compiler.
#
# usage: scripts/build-i686.sh [BUILD_DIR] [extra `meson setup` args...]
#
# packaging/meson-config/zig-x86.ini is portable. This script generates the only
# machine-specific part, BUILD_DIR.cross-local.ini (next to the build dir, never
# committed), from the environment:
#
#   VKHOOK_I686_PKG_CONFIG_LIBDIR  colon list of directories holding the 32-bit .pc
#                                  files. Default: the multilib locations that
#                                  exist (/usr/lib32/pkgconfig,
#                                  /usr/lib/i386-linux-gnu/pkgconfig) plus
#                                  /usr/share/pkgconfig for arch-independent
#                                  packages such as wayland-protocols.
#   VKHOOK_I686_DEPS               optional root of locally extracted 32-bit
#                                  packages (usr/lib32/{pkgconfig,*.so}), for
#                                  libraries the system lacks. Its pkgconfig dir is
#                                  searched first and its runtime libraries are
#                                  copied to BUILD_DIR/runtime-libs with an
#                                  $ORIGIN rpath, which the cross link and
#                                  `meson test` use.
#   VKHOOK_I686_SYSROOT_INCLUDE    header directory Zig does not search for a
#                                  foreign target. Default /usr/include.
#
# Needs zig and pkg-config; patchelf only when VKHOOK_I686_DEPS is set.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
build="${1:-build-i686}"
shift || true
build="$(realpath -m "$build")"

command -v zig >/dev/null || { echo "zig not found on PATH" >&2; exit 1; }

pc=()
if [[ -n "${VKHOOK_I686_DEPS:-}" ]]; then
    pc+=("$VKHOOK_I686_DEPS/usr/lib32/pkgconfig")
fi
if [[ -n "${VKHOOK_I686_PKG_CONFIG_LIBDIR:-}" ]]; then
    IFS=: read -r -a more <<<"$VKHOOK_I686_PKG_CONFIG_LIBDIR"
    pc+=("${more[@]}")
else
    for d in /usr/lib32/pkgconfig /usr/lib/i386-linux-gnu/pkgconfig /usr/share/pkgconfig; do
        [[ -d "$d" ]] && pc+=("$d")
    done
fi
include="${VKHOOK_I686_SYSROOT_INCLUDE:-/usr/include}"

quote_list() { local out="" x; for x in "$@"; do out+="'$x', "; done; printf '[%s]' "${out%, }"; }

local_ini="$build.cross-local.ini"
{
    echo "# generated by scripts/build-i686.sh; machine-specific, not committed"
    echo "[properties]"
    echo "pkg_config_libdir = $(quote_list "${pc[@]}")"
    echo "[built-in options]"
    echo "c_args = ['-idirafter', '$include']"
    echo "cpp_args = ['-idirafter', '$include']"
    # System 32-bit libraries are built against a newer glibc than the 2.34 the layer
    # targets (for example __isoc23_strtol@GLIBC_2.38 in libxkbcommon); they only need to
    # resolve at run time on the host, so the cross link must not reject them.
    link="'-Wl,--allow-shlib-undefined'"
    if [[ -n "${VKHOOK_I686_DEPS:-}" ]]; then
        link="'-Wl,-rpath,\$ORIGIN/runtime-libs', $link"
    fi
    echo "c_link_args = [$link]"
    echo "cpp_link_args = [$link]"
} >"$local_ini"

if [[ ! -f "$build/build.ninja" ]]; then
    meson setup "$build" "$root" \
        --cross-file "$root/packaging/meson-config/zig-x86.ini" \
        --cross-file "$local_ini" \
        --buildtype=release --prefix=/usr "$@"
fi
meson compile -C "$build"

if [[ -n "${VKHOOK_I686_DEPS:-}" ]]; then
    command -v patchelf >/dev/null || { echo "patchelf not found (needed to stage runtime libs)" >&2; exit 1; }
    mkdir -p "$build/runtime-libs"
    for lib in "$VKHOOK_I686_DEPS"/usr/lib32/*.so.[0-9]*; do
        [[ -L "$lib" ]] && continue
        name="$(basename "$lib")"
        install -m755 "$lib" "$build/runtime-libs/$name"
        patchelf --set-rpath '$ORIGIN' "$build/runtime-libs/$name"
    done
    for lib in "$VKHOOK_I686_DEPS"/usr/lib32/*.so.[0-9]; do
        [[ -L "$lib" ]] && ln -sfn "$(readlink "$lib")" "$build/runtime-libs/$(basename "$lib")"
    done
    ln -sfn ../runtime-libs "$build/src/runtime-libs"
fi
echo "i686 build in $build"
